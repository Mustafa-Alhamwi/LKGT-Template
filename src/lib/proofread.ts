const AR_LETTER = /[؀-ۿ]/
const AR_BOUNDARY = '(?<![\\u0600-\\u06FF])'
const AR_END = '(?![\\u0600-\\u06FF])'

export function proofread(text: string): Fix[] {
  const out: Fix[] = []
  if (!text.trim()) return out
  const hasAr = AR_LETTER.test(text)
  if (hasAr) {
    for (const [w, r] of WORDS) {
      if (w === r) continue
      const re = new RegExp(`${AR_BOUNDARY}${w}${AR_END}`, 'g')
      let m: RegExpExecArray | null
      while ((m = re.exec(text))) out.push({ wrong: m[0], right: r, reason: 'إملاء', index: m.index })
    }
    // علامات ترقيم لاتينية داخل نص عربي
    const punct: [RegExp, string, string][] = [
      [/(?<=[؀-ۿ])\s*,/g, '،', 'الفاصلة العربية «،»'],
      [/(?<=[؀-ۿ])\s*\?/g, '؟', 'علامة الاستفهام العربية «؟»'],
      [/(?<=[؀-ۿ])\s*;/g, '؛', 'الفاصلة المنقوطة العربية «؛»'],
    ]
    for (const [re, r, why] of punct) {
      let m: RegExpExecArray | null
      while ((m = re.exec(text))) out.push({ wrong: m[0], right: r, reason: why, index: m.index })
    }
    // مسافة قبل علامات الترقيم العربية
    let m: RegExpExecArray | null
    const before = /\s+([،؛؟!.:])/g
    while ((m = before.exec(text))) out.push({ wrong: m[0], right: m[1], reason: 'مسافة زائدة قبل علامة الترقيم', index: m.index })
    // غياب المسافة بعد الفاصلة
    const after = /([،؛؟])(?=[؀-ۿA-Za-z0-9])/g
    while ((m = after.exec(text))) out.push({ wrong: m[0], right: `${m[1]} `, reason: 'أضف مسافة بعد العلامة', index: m.index })
  }
  // مسافات مكرّرة
  const dbl = /[ \t]{2,}/g
  let m: RegExpExecArray | null
  while ((m = dbl.exec(text))) out.push({ wrong: m[0], right: ' ', reason: 'مسافات مكرّرة', index: m.index })
  // كلمات مكررة متتالية
  const rep = /(^|\s)([؀-ۿA-Za-z]{2,})\s+\2(?=\s|$|[.,،!؟])/g
  while ((m = rep.exec(text))) out.push({ wrong: `${m[2]} ${m[2]}`, right: m[2], reason: 'تكرار الكلمة', index: m.index + m[1].length })
  return out
}

/** تطبيق كل التصحيحات (من النهاية للبداية) */
export function applyFixes(text: string, fixes: Fix[]): string {
  let out = text
  for (const f of [...fixes].sort((a, b) => b.index - a.index)) {
    if (out.slice(f.index, f.index + f.wrong.length) === f.wrong) out = out.slice(0, f.index) + f.right + out.slice(f.index + f.wrong.length)
  }
  return out
}
